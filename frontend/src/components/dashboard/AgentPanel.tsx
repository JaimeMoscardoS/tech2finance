import { Sparkles } from "lucide-react";
import { useId, useMemo } from "react";
import { insightFacts, useInsight, type InsightProvider, type InsightState } from "../../insights.ts";
import { buildDemoPortfolio, deriveAgentFacts, type AgentFacts, type DemoPortfolio } from "../../dashboard-portfolio.ts";
import type { Level } from "../../types/level.ts";
import { DemoBadge, StatusChip } from "./basics.tsx";
import type { Lang } from "./copy.ts";
import { eur, num, pct, signedPct } from "./format.ts";
import "./dashboard.css";

const copy = {
  es: {
    title: "Asistente de IA", ai: "Redactado por IA", local: "Explicación local",
    loading: "El asistente está redactando sus observaciones…",
    fallback: "Sin conexión con el modelo de IA: se muestra una explicación local con las mismas cifras.",
    aiNote: "Texto generado por el modelo a partir de las cifras calculadas por código (abajo). Puede contener imprecisiones.",
    limits: "Contenido educativo y general. No son órdenes de compra o venta ni asesoramiento personalizado; las simulaciones no predicen ni garantizan rendimientos.",
    summary: "Resumen", observations: "Observaciones", review: "Puntos para reflexionar", scenarios: "Escenarios ficticios", assumptions: "Supuestos y límites",
    scenarioCol: "Si la renta variable variara…", impactCol: "Efecto aproximado en la cartera", scenarioNote: "Ejercicio de sensibilidad con datos DEMO; no es una predicción.",
  },
  en: {
    title: "AI assistant", ai: "Written by AI", local: "Local explanation",
    loading: "The assistant is writing its observations…",
    fallback: "No connection to the AI model: showing a local explanation with the same figures.",
    aiNote: "Text generated by the model from the figures computed by code (below). It may contain inaccuracies.",
    limits: "Educational, general content. These are not buy or sell orders or personalised advice; simulations neither predict nor guarantee returns.",
    summary: "Summary", observations: "Observations", review: "Points to think about", scenarios: "Fictional scenarios", assumptions: "Assumptions and limits",
    scenarioCol: "If equities moved by…", impactCol: "Approximate effect on the portfolio", scenarioNote: "Sensitivity exercise on DEMO data; not a forecast.",
  },
} as const;

export function AgentPanel({ level, facts, language = "es", insight }: { level: Level; facts: AgentFacts; language?: Lang; insight?: InsightState }) {
  const c = copy[language];
  const id = useId();
  const es = language === "es";
  const n = (v: number | null, d = 1) => (v == null ? (es ? "sin dato" : "no data") : num(v, language, d));
  return (
    <aside className="dash-card dash-agent" aria-labelledby={`${id}-t`} data-agent-level={level}>
      <header className="dash-card__head">
        <h3 id={`${id}-t`}><Sparkles size={18} aria-hidden="true" /> {c.title}</h3>
        <span className="dash-agent__tags"><DemoBadge language={language} label="DEMO" />{insight?.status === "ai" ? <StatusChip tone="info">{c.ai}</StatusChip> : <StatusChip tone="neutral" icon={false}>{c.local}</StatusChip>}</span>
      </header>
      {insight?.status === "loading" && <p className="dash-agent__sample" role="status">{c.loading}</p>}
      {insight?.status === "ai" && insight.insight && (
        <section className="dash-agent__ai" aria-label={c.ai}>
          <p className="dash-agent__lead">{insight.insight.summary}</p>
          {level !== "beginner" && <ul>{insight.insight.points.map((pt) => <li key={pt}>{pt}</li>)}</ul>}
          <p className="dash-agent__note">{c.aiNote}</p>
        </section>
      )}
      {insight?.status === "template" && <p className="dash-agent__sample">{c.fallback}</p>}

      <section aria-label={c.summary}>
          <h4>{c.summary}</h4>
          <p>{es
            ? `Tu cartera de ejemplo vale ${eur(facts.totalValue, language)}${facts.pnlPercent != null ? ` y su resultado es ${signedPct(facts.pnlPercent, language)} sobre lo invertido` : ""}. La parte más grande está en «${facts.topName}» (${pct(facts.topWeightPct, language, 0)}).`
            : `Your sample portfolio is worth ${eur(facts.totalValue, language)}${facts.pnlPercent != null ? ` and its result is ${signedPct(facts.pnlPercent, language)} on the amount invested` : ""}. The largest part is in “${facts.topName}” (${pct(facts.topWeightPct, language, 0)}).`}</p>
        </section>

      {level !== "beginner" && (
        <>
          <section aria-label={c.observations}>
            <h4>{c.observations}</h4>
            <ul>
              <li>{es ? `Concentración: «${facts.topName}» pesa ${pct(facts.topWeightPct, language, 0)} de la cartera.` : `Concentration: “${facts.topName}” weighs ${pct(facts.topWeightPct, language, 0)} of the portfolio.`}</li>
              <li>{es ? `La renta variable supone ${facts.equityWeightPct == null ? "un porcentaje sin dato" : pct(facts.equityWeightPct, language, 0)} del valor; el riesgo medio ponderado de los productos es ${n(facts.averageRisk)} sobre 7.` : `Equities make up ${facts.equityWeightPct == null ? "an unknown share" : pct(facts.equityWeightPct, language, 0)} of the value; the weighted average product risk is ${n(facts.averageRisk)} out of 7.`}</li>
              <li>{es ? `En la serie ${facts.realNav ? "(valores liquidativos reales de la CNMV)" : "DEMO"}, la volatilidad anualizada es ${facts.volatilityPct == null ? "sin dato" : pct(facts.volatilityPct, language)} y la mayor caída desde un máximo, ${facts.maxDrawdownPct == null ? "sin dato" : pct(facts.maxDrawdownPct, language)}.` : `In the ${facts.realNav ? "series (real CNMV net asset values)" : "DEMO series"}, annualised volatility is ${facts.volatilityPct == null ? "no data" : pct(facts.volatilityPct, language)} and the largest fall from a peak is ${facts.maxDrawdownPct == null ? "no data" : pct(facts.maxDrawdownPct, language)}.`}</li>
            </ul>
          </section>
          {level === "intermediate" && <section aria-label={c.review}>
            <h4>{c.review}</h4>
            <ul>
              <li>{es ? "¿Tu horizonte y tu necesidad de liquidez encajan con la parte invertida en renta variable?" : "Do your horizon and liquidity needs fit the part invested in equities?"}</li>
              <li>{es ? "¿Conoces los gastos corrientes (TER) de cada fondo y cómo restan rentabilidad?" : "Do you know each fund's ongoing charges (TER) and how they reduce returns?"}</li>
            </ul>
          </section>}
        </>
      )}

      {level === "advanced" && (
        <>
          <section aria-label={c.scenarios}>
            <h4>{c.scenarios} <DemoBadge language={language} /></h4>
            <table className="dash-agent__table">
              <caption className="dash-sr">{c.scenarios}</caption>
              <thead><tr><th scope="col">{c.scenarioCol}</th><th scope="col" className="is-num">{c.impactCol}</th></tr></thead>
              <tbody>{facts.scenarios.map((s) => <tr key={s.equityShockPct}><th scope="row">{signedPct(s.equityShockPct, language, 0)}</th><td className="is-num">{s.portfolioImpactPct == null ? (es ? "sin dato" : "no data") : signedPct(s.portfolioImpactPct, language)}</td></tr>)}</tbody>
            </table>
            <p className="dash-agent__note">{c.scenarioNote}</p>
          </section>
          <section aria-label={c.assumptions}>
            <h4>{c.assumptions}</h4>
            <ul>
              <li>{es ? `Efecto = exposición a renta variable (${facts.equityExposurePct == null ? "sin dato" : pct(facts.equityExposurePct, language)}, incluida la parte de renta variable del fondo mixto) × variación supuesta; el resto de activos no cambia. Sin efecto de divisa.` : `Effect = equity exposure (${facts.equityExposurePct == null ? "not available" : pct(facts.equityExposurePct, language)}, including the equity part of the mixed fund) × assumed move; other assets unchanged. No currency effect.`}</li>
              <li>{es ? `Sharpe anualizado ${n(facts.sharpe, 2)} con tipo libre de riesgo supuesto del ${pct(facts.riskFreeAnnualPct, language)}, sobre ${facts.monthlyObservations} rentabilidades mensuales ${facts.realNav ? "reales (valores liquidativos de la CNMV, netas de los gastos del fondo)" : "ficticias netas de gastos y sin tipo de cambio"} (se muestra «sin dato» con menos de 12).` : `Annualised Sharpe ${n(facts.sharpe, 2)} with an assumed risk-free rate of ${pct(facts.riskFreeAnnualPct, language)}, over ${facts.monthlyObservations} ${facts.realNav ? "real monthly returns (CNMV net asset values, net of fund costs)" : "fictional monthly returns, net of fees and without exchange rate"} (shown as “no data” with fewer than 12).`}</li>
              <li>{es ? "Sin costes de transacción, impuestos ni correlaciones cambiantes: simplificación didáctica." : "No transaction costs, taxes or changing correlations: a didactic simplification."}</li>
            </ul>
          </section>
        </>
      )}
      {level === "beginner" && <p className="dash-agent__note">{es ? "Pregunta al tutor si algún término no te queda claro (por ejemplo, «diversificar»)." : "Ask the tutor if a term is unclear (for example, “diversification”)."}</p>}
      <p className="dash-agent__limits">{c.limits}</p>
    </aside>
  );
}

/** Panel listo para colocar en el dashboard: calcula los datos con la cartera indicada (por defecto la DEMO) y el código de métricas. */
export function AgentPanelSection({ level, language = "es", portfolio, insights }: { level: Level; language?: Lang; portfolio?: DemoPortfolio; insights?: InsightProvider }) {
  const p = useMemo(() => portfolio ?? buildDemoPortfolio(), [portfolio]);
  const facts = useMemo(() => deriveAgentFacts(p), [p]);
  const request = useMemo(() => ({ kind: "agent" as const, page: "portfolio" as const, level, language, facts: insightFacts(p) }), [p, level, language]);
  const insight = useInsight(insights, request);
  return <div data-tour="agent-portfolio"><AgentPanel level={level} facts={facts} language={language} insight={insight} /></div>;
}
